"""
Genera los dispositivos de Norteamerica (EE. UU. continental + sur de Canada) para los escenarios fuera de Europa.

Mismo formato que devices/WorldWide-N-ML.ini de Test_KD:
    - deploymentRadius = 0 y posicion fija (centerLatitude, centerLongitude)
    - anidados: los primeros N terminales del archivo de 1000 son exactamente los del archivo de N
    - separacion minima entre dos dispositivos: 8 km
Las posiciones se sortean uniformes (en area) dentro de un poligono aproximado de tierra firme; pueden caer algunos
puntos en lagos (Grandes Lagos), que para la simulacion es solo una posicion.

Uso:  python3 make_devices_na.py      (escribe en ../devices/)
"""
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "devices")
SIZES = [60, 100, 300, 500, 1000]
MIN_SEPARATION_KM = 8.0
SEED = 20261120
EARTH_RADIUS_KM = 6371.0

# Poligono (longitud, latitud) de EE. UU. continental + franja sur de Canada (hasta ~54 N, sin la bahia de James)
POLYGON = [
    (-124.6, 48.4), (-124.1, 46.2), (-124.0, 43.0), (-124.3, 40.4), (-122.6, 37.8), (-120.6, 34.6), (-117.2, 32.6),
    (-114.7, 32.7), (-111.0, 31.3), (-108.2, 31.3), (-106.5, 31.8), (-104.5, 29.6), (-101.4, 29.8), (-99.5, 27.5),
    (-97.4, 26.0), (-97.4, 27.8), (-94.5, 29.5), (-92.0, 29.6), (-89.6, 29.9), (-88.0, 30.4), (-85.9, 30.2),
    (-84.3, 30.0), (-82.7, 28.0), (-81.8, 26.1), (-80.4, 25.3), (-80.1, 26.9), (-81.4, 30.5), (-80.9, 32.1),
    (-78.0, 33.9), (-75.6, 35.3), (-76.0, 36.9), (-75.0, 38.6), (-74.0, 40.6), (-72.0, 41.0), (-70.0, 41.7),
    (-70.6, 42.7), (-70.0, 43.7), (-67.0, 44.8), (-67.8, 47.1), (-70.0, 47.5), (-72.0, 48.4), (-72.0, 51.0),
    (-84.0, 51.0), (-90.0, 53.0), (-100.0, 54.0), (-110.0, 54.0), (-120.0, 54.0), (-125.5, 50.5), (-123.3, 49.0),
]


def inside_polygon(lon, lat, polygon):
    """Ray casting: True si (lon, lat) esta dentro del poligono."""
    inside = False
    n = len(polygon)
    j = n - 1
    for i in range(n):
        xi, yi = polygon[i]
        xj, yj = polygon[j]
        crosses = (yi > lat) != (yj > lat)
        if crosses:
            x_cross = (xj - xi) * (lat - yi) / (yj - yi) + xi
            if lon < x_cross:
                inside = not inside
        j = i
    return inside


def distance_km(lat1, lon1, lat2, lon2):
    """Haversine; lat2/lon2 pueden ser arrays."""
    p1, p2 = np.radians(lat1), np.radians(lat2)
    dp = p2 - p1
    dl = np.radians(lon2 - lon1)
    h = np.sin(dp / 2) ** 2 + np.cos(p1) * np.cos(p2) * np.sin(dl / 2) ** 2
    return 2 * EARTH_RADIUS_KM * np.arcsin(np.sqrt(h))


def sample_devices(n_total, rng):
    lons = [p[0] for p in POLYGON]
    lats = [p[1] for p in POLYGON]
    lat_min, lat_max = min(lats), max(lats)
    lon_min, lon_max = min(lons), max(lons)
    chosen_lat = []
    chosen_lon = []
    while len(chosen_lat) < n_total:
        # uniforme en area: sin(lat) uniforme
        lat = np.degrees(np.arcsin(rng.uniform(np.sin(np.radians(lat_min)), np.sin(np.radians(lat_max)))))
        lon = rng.uniform(lon_min, lon_max)
        if not inside_polygon(lon, lat, POLYGON):
            continue
        if chosen_lat:
            nearest = distance_km(lat, lon, np.array(chosen_lat), np.array(chosen_lon)).min()
            if nearest < MIN_SEPARATION_KM:
                continue
        chosen_lat.append(round(lat, 3))
        chosen_lon.append(round(lon, 3))
    return chosen_lat, chosen_lon


def write_file(path, n, lat, lon):
    lines = [
        "# =====================================================================",
        f"# INFERENCE / CLOSED-LOOP ROBUSTNESS SET - {n} DEVICES (North America: contiguous USA + southern Canada)",
        "# Outside the training region (Europe). Uniform in area inside an approximate land polygon.",
        f"# min. separation between any two devices: {MIN_SEPARATION_KM:.0f} km. Generated by tools/make_devices_na.py (seed {SEED}).",
        "# Nested: the first N terminals equal NorthAmerica-N-ML.ini for smaller N.",
        f"# Requires: **.numTerminals = {n}",
        "# =====================================================================",
        "",
    ]
    for k in range(n):
        lines.append(f"*.terminal[{k}].mob.deploymentRadius = 0.0")
        lines.append(f"*.terminal[{k}].mob.centerLatitude = {lat[k]:.3f}")
        lines.append(f"*.terminal[{k}].mob.centerLongitude = {lon[k]:.3f}")
        lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main():
    rng = np.random.default_rng(SEED)
    lat, lon = sample_devices(max(SIZES), rng)
    os.makedirs(OUT, exist_ok=True)
    for n in SIZES:
        write_file(os.path.join(OUT, f"NorthAmerica-{n}-ML.ini"), n, lat, lon)
    print(f"lat {min(lat)} .. {max(lat)}  lon {min(lon)} .. {max(lon)}  media lat {np.mean(lat):.2f} lon {np.mean(lon):.2f}")


if __name__ == "__main__":
    main()
