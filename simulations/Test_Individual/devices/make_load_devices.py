#!/usr/bin/env python3
"""Write a device file for the load sweep by cycling over the 60 closed-loop centres.

Each terminal keeps a centre from WorldWide-60_closed_loop_ML_unique.ini, so geography stays the
same as the LATINCOM closed loop. Ter_Mob spreads terminals around their centre with its default
deployment radius, so terminals that share a centre do not share a position.

Usage: make_load_devices.py [count]   (default 960, run from this folder)
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
SOURCE = HERE / "WorldWide-60_closed_loop_ML_unique.ini"
COUNT = int(sys.argv[1]) if len(sys.argv) > 1 else 960

centres = {}
for line in SOURCE.read_text().splitlines():
    m = re.match(r"\*\.terminal\[(\d+)\]\.mob\.center(Latitude|Longitude)\s*=\s*([-\d.]+)", line.strip())
    if m:
        centres.setdefault(int(m.group(1)), {})[m.group(2)] = m.group(3)
if len(centres) != 60:
    sys.exit(f"expected 60 centres, found {len(centres)}")

out = [f"# Generated by make_load_devices.py: {COUNT} terminals over the 60 closed-loop centres.", ""]
for i in range(COUNT):
    c = centres[i % 60]
    out.append(f"*.terminal[{i}].mob.centerLatitude = {c['Latitude']}")
    out.append(f"*.terminal[{i}].mob.centerLongitude = {c['Longitude']}")
(HERE / f"WorldWide-{COUNT}_closed_loop_load.ini").write_text("\n".join(out) + "\n")
print(f"wrote {COUNT} terminals")
